"""PDF receipts and incident reports, with charts drawn from the case record.

Two audiences share one builder:

* ``analyst``: the full incident report for the fraud desk.
* ``customer``: a plain-language receipt with masked identifiers.

Charts are drawn with fpdf2 primitives from the stored events, so every bar and
every point comes from the case data. Nothing is generated by a model.

A report is rebuilt from events up to the moment it was filed, with that moment
as the PDF creation date. The same case therefore always yields the same bytes,
and the SHA-256 stored on the report row can be re-checked on download.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from fpdf import FPDF

from app.db import session_scope
from app.models import Case, CaseEvent, Report, Transaction, User
from app.util import aware, lkr

# Palette. Teal is the brand; outcome colours are only used for the outcome.
INK = (24, 33, 38)
MUTED = (96, 108, 114)
RULE = (214, 220, 222)
SOFT = (241, 245, 245)
TEAL = (21, 111, 107)
LOGO = Path(__file__).with_name("assets") / "logo.png"
TEAL_SOFT = (214, 236, 234)
OUTCOME = {
    "closed_blocked": ((176, 36, 36), (251, 233, 233), "PAYMENT BLOCKED"),
    "closed_released": ((22, 120, 72), (226, 244, 234), "PAYMENT RELEASED"),
    "closed_cleared": ((22, 120, 72), (226, 244, 234), "PAYMENT RELEASED"),
    "escalated": ((168, 104, 0), (252, 241, 220), "HELD - WITH AN ANALYST"),
}
DEFAULT_OUTCOME = ((96, 108, 114), (238, 241, 242), "IN PROGRESS")


@dataclass
class Milestone:
    at: datetime
    label: str
    kind: str  # "info", "good", "bad", "wait"


def _latin(text: str) -> str:
    return (text or "").replace("—", "-").replace("–", "-").replace("’", "'").encode("latin-1", "replace").decode("latin-1")


def _tail(value: str | None, keep: int = 2) -> str:
    digits = "".join(ch for ch in (value or "") if ch.isdigit())
    return f"..{digits[-keep:]}" if digits else "-"


def _clock(moment: datetime | None) -> str:
    """Exact Asia/Colombo time to the second."""
    if moment is None:
        return "-"
    from zoneinfo import ZoneInfo

    return aware(moment).astimezone(ZoneInfo("Asia/Colombo")).strftime("%d %b %Y %H:%M:%S")


def milestones(events: list[CaseEvent]) -> list[Milestone]:
    """The steps a customer or analyst cares about, in order, from the raw agent events."""
    found: list[Milestone] = []
    seen: set[str] = set()
    rounds = 0
    events = [e for e in events if getattr(e, "phase", None) != "started"]

    def add(event: CaseEvent, label: str, kind: str, once: bool = True) -> None:
        if once and label in seen:
            return
        seen.add(label)
        found.append(Milestone(aware(event.created_at), label, kind))

    for event in events:
        tool = event.tool_name or ""
        summary = (event.result_summary or event.message or "").lower()
        if tool == "create_case":
            add(event, "Case opened", "info")
        elif tool == "get_sim_swap_status":
            add(event, "SIM swap found" if "swapped" in summary and "no sim swap" not in summary else "SIM checked", "bad" if "was swapped" in summary else "info")
        elif tool == "hold_transaction":
            add(event, "Payment held", "wait")
        elif tool in {"send_push", "send_email", "send_sms"} and event.agent == "alert":
            add(event, "Customer alerted", "info")
        elif event.agent == "customer" and event.state == "done":
            add(event, "Customer said yes" if "yes" in summary else "Customer said no", "info")
        elif tool == "liveness_check":
            add(event, "Selfie live" if summary.startswith("live") else "Selfie rejected", "good" if summary.startswith("live") else "bad", once=False)
        elif tool == "ask_security_questions":
            rounds += 1
            matched = "matched" in summary
            add(event, f"Round {rounds} {'passed' if matched else 'failed'}", "good" if matched else "bad", once=False)
        elif tool == "release_transaction":
            add(event, "Payment released", "good")
        elif tool == "block_transaction":
            add(event, "Payment blocked", "bad")
        elif tool == "request_sim_freeze":
            add(event, "Freeze logged", "bad")
        elif tool == "lock_account":
            add(event, "Account locked", "bad")
        elif event.agent == "supervisor" and "analyst" in summary:
            add(event, "Sent to analyst", "wait")
        elif tool == "generate_report":
            add(event, "Report filed", "info")
    return found


class _Doc(FPDF):
    def __init__(self, title: str, reference: str, created: datetime):
        super().__init__(unit="mm", format="A4")
        self._title = title
        self._reference = reference
        # Reports are a few pages. Uncompressed text keeps them searchable and byte-for-byte reproducible.
        self.set_compression(False)
        self.set_creation_date(aware(created))
        self.set_title(title)
        self.set_author("PayShield")
        self.set_creator("PayShield report agent")
        self.set_auto_page_break(auto=True, margin=18)
        self.set_margins(16, 16, 16)
        self.alias_nb_pages()

    def header(self) -> None:
        self.set_fill_color(*TEAL)
        self.rect(0, 0, self.w, 4, "F")
        if self.page_no() > 1:
            self.set_y(8)
            self.set_font("Helvetica", "", 8)
            self.set_text_color(*MUTED)
            self.cell(0, 4, _latin(f"{self._title}  |  {self._reference}" if self._reference else self._title), align="R")
            self.ln(8)

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*MUTED)
        self.cell(0, 4, "PayShield pilot. Simulated network. Not connected to a live bank or operator.", align="L")
        self.cell(0, 4, f"Page {self.page_no()} of {{nb}}", align="R")

    # Building blocks

    def heading(self, text: str) -> None:
        if self.get_y() > self.h - 50:
            self.add_page()
        self.ln(3)
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(*TEAL)
        self.cell(0, 6, _latin(text.upper()), new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(*RULE)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(2.5)
        self.set_text_color(*INK)

    def para(self, text: str, size: float = 9.5, color=INK) -> None:
        self.set_font("Helvetica", "", size)
        self.set_text_color(*color)
        self.multi_cell(self.epw, 4.8, _latin(text), new_x="LMARGIN", new_y="NEXT")

    def facts(self, rows: list[tuple[str, str]], columns: int = 2) -> None:
        width = self.epw / columns
        self.set_font("Helvetica", "", 9)
        for start in range(0, len(rows), columns):
            y = self.get_y()
            for index, (label, value) in enumerate(rows[start:start + columns]):
                x = self.l_margin + index * width
                self.set_xy(x, y)
                self.set_text_color(*MUTED)
                self.set_font("Helvetica", "", 7.5)
                self.cell(width, 3.8, _latin(label.upper()))
                self.set_xy(x, y + 3.8)
                self.set_text_color(*INK)
                self.set_font("Helvetica", "B", 9.5)
                self.cell(width - 3, 5, _latin(value)[:60])
            self.set_y(y + 11)

    def banner(self, status: str, line: str) -> None:
        strong, soft, word = OUTCOME.get(status, DEFAULT_OUTCOME)
        y = self.get_y()
        self.set_fill_color(*soft)
        self.rect(self.l_margin, y, self.epw, 17, "F")
        self.set_fill_color(*strong)
        self.rect(self.l_margin, y, 2.2, 17, "F")
        self.set_xy(self.l_margin + 6, y + 2.6)
        self.set_text_color(*strong)
        self.set_font("Helvetica", "B", 12)
        self.cell(0, 6, word)
        self.set_xy(self.l_margin + 6, y + 9)
        self.set_text_color(*INK)
        self.set_font("Helvetica", "", 9.5)
        self.cell(0, 5, _latin(line)[:110])
        self.set_y(y + 21)

    # Charts

    def timeline_chart(self, marks: list[Milestone], status: str) -> None:
        """One point per milestone, evenly spaced so labels never collide.
        The exact seconds since the case opened sit under each point."""
        if not marks:
            self.para("No milestones were recorded.", color=MUTED)
            return
        height = 50
        if self.get_y() + height > self.h - 20:
            self.add_page()
        top = self.get_y()
        left = self.l_margin + 10
        right = self.w - self.r_margin - 10
        axis = top + 23
        start = marks[0].at
        span = max(0.0, (marks[-1].at - start).total_seconds())
        colour = {"good": (22, 120, 72), "bad": (176, 36, 36), "wait": (168, 104, 0), "info": TEAL}
        count = len(marks)
        step = (right - left) / max(1, count - 1)
        label_w = min(34.0, step * 2 - 2)

        self.set_fill_color(*SOFT)
        self.rect(self.l_margin, top, self.epw, height, "F")
        self.set_draw_color(*RULE)
        self.set_line_width(0.6)
        self.line(left, axis, right, axis)
        for index, mark in enumerate(marks):
            x = left + step * index if count > 1 else (left + right) / 2
            above = index % 2 == 0
            self.set_draw_color(*RULE)
            self.set_line_width(0.2)
            self.line(x, axis + (-1.6 if above else 1.6), x, axis + (-6 if above else 6))
            self.set_fill_color(*colour.get(mark.kind, TEAL))
            self.ellipse(x - 1.5, axis - 1.5, 3, 3, "F")
            lx = max(self.l_margin + 1, min(x - label_w / 2, self.w - self.r_margin - label_w - 1))
            self.set_font("Helvetica", "B" if mark.kind in {"good", "bad"} else "", 6.8)
            self.set_text_color(*INK)
            self.set_xy(lx, axis - 15.5 if above else axis + 6.5)
            self.multi_cell(label_w, 3, _latin(mark.label), align="C", max_line_height=3)
            self.set_font("Helvetica", "", 6.2)
            self.set_text_color(*MUTED)
            offset = int((mark.at - start).total_seconds())
            self.set_xy(lx, axis - 9.4 if above else axis + 12.6)
            self.cell(label_w, 3, f"+{offset}s", align="C")
        self.set_xy(self.l_margin + 3, top + height - 5.5)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(*MUTED)
        self.cell(0, 4, _latin(f"Points are in order. Start {_clock(marks[0].at)} SLT, end {_clock(marks[-1].at)} SLT, {int(span)} seconds in all."))
        self.set_y(top + height + 3)
        self.set_text_color(*INK)

    def bar_chart(self, rows: list[tuple[str, float]], unit: str, colour=TEAL, cap: float | None = None) -> None:
        """Horizontal bars, one per row, with the value printed at the end."""
        if not rows:
            self.para("Nothing to chart.", color=MUTED)
            return
        label_w = 80
        bar_h = 5.2
        gap = 2.2
        height = len(rows) * (bar_h + gap) + 4
        if self.get_y() + height > self.h - 20:
            self.add_page()
        top = self.get_y() + 1
        track = self.epw - label_w - 16
        largest = cap or max(value for _label, value in rows) or 1
        for index, (label, value) in enumerate(rows):
            y = top + index * (bar_h + gap)
            self.set_xy(self.l_margin, y + 0.6)
            self.set_font("Helvetica", "", 8.2)
            self.set_text_color(*INK)
            self.cell(label_w - 2, 4, _latin(label)[:56])
            self.set_fill_color(*SOFT)
            self.rect(self.l_margin + label_w, y, track, bar_h, "F")
            self.set_fill_color(*colour)
            self.rect(self.l_margin + label_w, y, max(0.8, track * min(1.0, value / largest)), bar_h, "F")
            self.set_xy(self.l_margin + label_w + track + 1.5, y + 0.6)
            self.set_font("Helvetica", "B", 8.2)
            self.cell(14, 4, f"{value:g}{unit}")
        self.set_y(top + height)

    def event_table(self, events: list[CaseEvent], customer: bool) -> None:
        widths = (34, 24, 32, self.epw - 90)
        heads = ("Time (SLT)", "Agent", "Step", "What happened")
        self.set_font("Helvetica", "B", 7.6)
        self.set_fill_color(*TEAL_SOFT)
        self.set_text_color(*INK)
        for width, head in zip(widths, heads, strict=False):
            self.cell(width, 5.5, head, fill=True)
        self.ln(5.5)
        self.set_font("Helvetica", "", 7.4)
        for index, event in enumerate(events):
            text = " ".join((event.result_summary or event.message or "").split())
            if customer:
                text = text.replace("HMAC-SHA256 ok, nonce fresh, ", "verified, ")
            text = _latin(text)[:320]
            step = event.tool_name or event.state
            lines = max(1, int(self.get_string_width(text) / (widths[3] - 6)) + 1)
            row_h = 4.2 * lines
            if self.get_y() + row_h > self.h - 18:
                self.add_page()
            y = self.get_y()
            if index % 2:
                self.set_fill_color(*SOFT)
                self.rect(self.l_margin, y, self.epw, row_h, "F")
            self.set_text_color(*MUTED)
            self.cell(widths[0], 4.2, _clock(event.created_at))
            self.set_text_color(*INK)
            self.cell(widths[1], 4.2, _latin(event.agent))
            self.cell(widths[2], 4.2, _latin(step)[:22])
            self.multi_cell(widths[3], 4.2, text, new_x="LMARGIN", new_y="NEXT")
            self.set_y(max(self.get_y(), y + row_h))


_OUTCOME_LINE = {
    "closed_blocked": "The transfer was stopped. The account and SIM are protected.",
    "closed_released": "You confirmed the payment and passed the checks. It was released.",
    "closed_cleared": "The payment was low risk and went through.",
    "escalated": "There was no answer in time. The money is still held and a person has the case.",
}


def _customer_steps(case: Case, restricted: bool) -> list[str]:
    if case.status == "closed_blocked":
        steps = [
            "The transfer is blocked and no money left your account.",
            f"We recorded a SIM freeze request, reference {case.sim_freeze_ref}. Your mobile operator has not been told, so call them to freeze the SIM." if case.sim_freeze_ref else "No SIM freeze request was recorded on this case.",
            "Transfers, new payees, password resets and port-out stay locked until the fraud desk clears them." if restricted else "No account limits were applied.",
            "Call your bank on the number printed on your card. Do not use a number from a text message.",
        ]
    elif case.status in {"closed_released", "closed_cleared"}:
        steps = [
            "The payment went through as you asked.",
            "If you did not make this payment after all, call your bank on the number printed on your card.",
        ]
    elif case.status == "escalated":
        steps = [
            "The money is still held. Nothing has left your account.",
            "A person on the fraud desk will call you on your registered number.",
        ]
    else:
        steps = ["This case is still open. Check the PayShield app for the next step."]
    steps.append("PayShield will never ask you for a password or a code by SMS or phone call.")
    return steps


def build_case_pdf(case_id: str, audience: str = "analyst", show_case_line: bool = True) -> bytes:
    """show_case_line=False leaves the case number and filing time off the title block and the page header (used for the
    sample reports in docs/samples)."""
    if audience not in {"analyst", "customer"}:
        raise ValueError("audience must be analyst or customer")
    customer = audience == "customer"
    with session_scope() as session:
        case = session.get(Case, case_id)
        if case is None:
            raise LookupError(case_id)
        user = session.get(User, case.customer_id)
        tx = session.get(Transaction, case.transaction_id) if case.transaction_id else None
        report = session.query(Report).filter(Report.case_id == case_id).one_or_none()
        cutoff = aware(report.created_at) if report is not None else None
        query = session.query(CaseEvent).filter(CaseEvent.case_id == case_id)
        events = [e for e in query.order_by(CaseEvent.created_at.asc(), CaseEvent.id.asc()).all() if e.phase != "started"]  # a start marker is progress, not an outcome
        if cutoff is not None:
            events = [event for event in events if aware(event.created_at) <= cutoff]
        for item in (case, user, tx, report, *events):
            if item is not None:
                session.expunge(item)

    created = cutoff or aware(case.updated_at)
    title = "Payment receipt" if customer else "Incident report"
    doc = _Doc(f"PayShield {title.lower()}", case.id if show_case_line else "", created)
    doc.add_page()

    # Title block
    doc.image(str(LOGO), x=16, y=11, h=10)
    doc.set_y(24)
    doc.set_font("Helvetica", "B", 19)
    doc.set_text_color(*INK)
    doc.cell(0, 9, title, new_x="LMARGIN", new_y="NEXT")
    doc.set_font("Helvetica", "", 9)
    doc.set_text_color(*MUTED)
    if show_case_line:
        doc.cell(0, 5, _latin(f"Case {case.id}  |  Filed {_clock(created)} Asia/Colombo"), new_x="LMARGIN", new_y="NEXT")
    doc.ln(4)

    payee = case.payee or (tx.payee if tx else "")
    doc.banner(case.status, f"{lkr(case.amount_lkr)} to {payee}. {_OUTCOME_LINE.get(case.status, 'The case is still open.')}")

    marks = milestones(events)
    by_label = {mark.label: mark.at for mark in marks}
    started = marks[0].at if marks else aware(case.created_at)
    decided_at = by_label.get("Payment released") or by_label.get("Payment blocked") or by_label.get("Sent to analyst")

    if customer:
        doc.facts(
            [
                ("Customer", user.full_name if user else "-"),
                ("Bank", user.bank if user else "-"),
                ("Account", _tail(user.account_number if user else "", 4)),
                ("Registered mobile", _tail(user.phone if user else "", 2)),
                ("Amount", lkr(case.amount_lkr)),
                ("Payee", payee or "-"),
                ("Payment attempted", _clock(tx.occurred_at if tx else case.created_at)),
                ("Outcome recorded", _clock(decided_at) if decided_at else "-"),
            ]
        )
    else:
        doc.facts(
            [
                ("Customer", user.full_name if user else "-"),
                ("Bank / branch", f"{user.bank} / {user.branch}" if user else "-"),
                ("Account", user.account_number if user else "-"),
                ("Mobile", user.phone if user else "-"),
                ("District / province", f"{user.district} / {user.province}" if user else "-"),
                ("Transaction", tx.id if tx else (case.transaction_id or "-")),
                ("Amount / payee", f"{lkr(case.amount_lkr)} / {payee}"),
                ("Ledger status", tx.status if tx else "-"),
                ("Risk score", f"{case.risk_score if case.risk_score is not None else '-'} / 100"),
                ("Rule decision", case.policy_decision or "-"),
                ("Customer answer", case.customer_decision or "none"),
                ("Face check", f"{case.face_score:g} / 100 ({case.face_verdict})" if case.face_score is not None else (case.face_verdict or "not used")),
                ("SIM freeze", case.sim_freeze_ref or "not requested"),
                ("Time to outcome", f"{int((decided_at - started).total_seconds())} s" if decided_at else "-"),
                ("Alerts sent", str(case.alert_count or 0)),
            ]
        )

    doc.heading("What happened, and when")
    doc.timeline_chart(marks, case.status)

    if customer:
        doc.heading("What this means for you")
        for index, step in enumerate(_customer_steps(case, bool(user and user.restricted)), start=1):
            doc.para(f"{index}.  {step}")
        doc.heading("Why the payment was checked")
        reasons = [str(item.get("label")) for item in (case.risk_factors or []) if (item.get("points") or 0) > 0][:5]
        # Lower-case the first letter, but leave acronyms such as SIM alone.
        reasons = [reason if reason[1:2].isupper() else reason[:1].lower() + reason[1:] for reason in reasons]
        doc.para(
            "The payment was checked because: "
            + ("; ".join(reasons) if reasons else "the bank's fraud rules flagged it")
            + ". The decision was made by fixed bank rules, not by an AI model."
        )
    else:
        doc.heading("Risk factors (points added to the score)")
        factors = [(str(item.get("label")), float(item.get("points") or 0)) for item in (case.risk_factors or [])]
        added = [row for row in factors if row[1] > 0]
        taken_off = [row for row in factors if row[1] < 0]
        doc.bar_chart(sorted(added, key=lambda row: -row[1]), "", colour=(176, 36, 36) if (case.risk_score or 0) >= 45 else TEAL)
        if taken_off:
            doc.para("Taken off for usual behaviour: " + "; ".join(f"{label} ({points:g})" for label, points in taken_off), size=8.5, color=MUTED)
        doc.para(
            f"The factors add to {sum(points for _label, points in factors):g}; the score is kept between 0 and 100. "
            "The score is an input. The rule layer decides hold, block or release; the model only writes notes.",
            size=8.5,
            color=MUTED,
        )

        doc.heading("Work done by each agent")
        counts: dict[str, int] = {}
        for event in events:
            counts[event.agent] = counts.get(event.agent, 0) + 1
        doc.bar_chart(sorted(counts.items(), key=lambda row: -row[1]), " steps")
        reviews = [event for event in events if event.tool_name == "review_notes" and event.state == "calling_tool"]
        if reviews:
            doc.para("Note review by the report agent: " + _latin(str(reviews[-1].result_summary or "")) + ".", size=8.5, color=MUTED)
        verified = sum(1 for event in events if event.tool_name == "verify_handoff" and event.state == "calling_tool")
        rejected = sum(1 for event in events if event.tool_name == "verify_handoff" and event.state == "error")
        doc.para(
            f"Signed handoffs verified: {verified}. Rejected: {rejected}. "
            "Each handoff carries an HMAC-SHA256 signature, a nonce and a timestamp, and is checked before the next agent acts.",
            size=8.5,
            color=MUTED,
        )

        doc.heading("Agent notes")
        for label, note in (("Telecom", case.telecom_summary), ("Banking", case.banking_summary), ("Risk", case.risk_summary)):
            if note:
                doc.set_font("Helvetica", "B", 9)
                doc.cell(0, 5, label, new_x="LMARGIN", new_y="NEXT")
                doc.para(note, size=9)
        doc.para(case.policy_reason or "", size=9)

    doc.heading("Full timeline" if not customer else "Every step, to the second")
    shown = events if not customer else [event for event in events if event.state in {"calling_tool", "done", "waiting_for_customer"} and event.agent != "case"]
    doc.event_table(shown, customer)

    doc.heading("Integrity")
    body = "\n".join(f"{event.created_at.isoformat()}|{event.agent}|{event.tool_name}|{event.result_summary or event.message}" for event in events)
    digest = hashlib.sha256(body.encode()).hexdigest()
    doc.para(
        f"Timeline fingerprint (SHA-256): {digest}\n"
        + ("Your bank can match this fingerprint to its own record of the case." if customer else
           "The stored PDF fingerprint is on the report record. The operator audit log is a SHA-256 hash chain checked on the Security page."),
        size=8,
        color=MUTED,
    )
    output = doc.output()
    return bytes(output) if not isinstance(output, str) else output.encode("latin-1")

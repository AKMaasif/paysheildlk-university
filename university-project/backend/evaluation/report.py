"""Turns results.json into results.md and charts."""

from pathlib import Path

PCT = lambda x: "n/a" if x is None else f"{x * 100:.1f}%"


def _table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def write_report(res: dict, out: Path) -> None:
    meta, system, agents, base, inj = res["meta"], res["system"], res["agents"], res["single_agent_baseline"], res["injection"]
    o = system["overall"]
    md: list[str] = []
    md.append("# Evaluation results\n")
    md.append(
        f"Generated by `python -m evaluation.run` (seed {meta['seed']}, {meta['cases']} cases, {meta['seconds']} s). "
        f"Model: **{meta['model']}**.\n\n"
        "**Read this first.** All data is synthetic. A scenario's fraud label comes from how the scenario was built, "
        "not from the rules, so the rules can be wrong and the harness counts it. These numbers show how this design behaves "
        "on invented cases. They say nothing about real customers or real fraud rates. With no model key, every model-written "
        "note is the deterministic mock, so notes are checked for plumbing and privacy, not for quality.\n"
    )

    md.append("## 1. The whole system on every scenario\n")
    md.append("Flagged means the rules held or blocked the payment. Fraud that is released is a miss. A legitimate payment that is held is a false hold.\n")
    md.append(_table(["Cases", "Accuracy", "Precision", "Recall", "False-hold rate", "Missed-fraud rate"],
                     [[o["n"], PCT(o["accuracy"]), PCT(o["precision"]), PCT(o["recall"]), PCT(o["false_hold_rate"]), PCT(o["missed_fraud_rate"])]]))
    md.append("\n### By scenario type\n")
    md.append(_table(["Group", "Scenario", "Truth", "Cases", "Flagged", "Release", "Hold", "Block"],
                     [[a["group"], a["archetype"], "fraud" if a["fraud"] else "legitimate", a["n"], PCT(a["flag_rate"]), a["decisions"]["release"], a["decisions"]["hold"], a["decisions"]["block"]] for a in system["by_archetype"]]))
    bg = system["by_group"]
    md.append("\n### By group\n")
    md.append(_table(["Group", "Cases", "Missed-fraud rate", "False-hold rate"],
                     [["benign", bg["benign"]["n"], "n/a", PCT(bg["benign"]["false_hold_rate"])],
                      ["attack (the patterns the rules were written for)", bg["attack"]["n"], PCT(bg["attack"]["missed_fraud_rate"]), "n/a"],
                      ["adversarial (red team, shaped to slip under thresholds)", bg["adversarial"]["n"], PCT(bg["adversarial"]["missed_fraud_rate"]), "n/a"]]))
    lat = system["latency_s"]
    md.append(
        f"\n- Time to a decision, multi-agent graph: p50 {lat['p50'] * 1000:.0f} ms, p95 {lat['p95'] * 1000:.0f} ms (mock model, no step delay).\n"
        f"- Texts handed to the model layer: {system['model_texts_seen']}. With a raw phone, NIC, email or account number still in them: **{system['model_texts_with_raw_identifiers']}**.\n"
        f"- Agent tool calls: {system['tool_calls']}. Outside the agent's charter: **{system['tool_calls_outside_charter']}**.\n"
        f"- Cases that ended with no decision: **{system['cases_with_no_decision']}**.\n"
    )

    md.append("## 2. Each agent on its own\n")
    rows = []
    for name, checks in agents.items():
        for c in checks:
            rate = "n/a" if c["total"] == 0 else f"{c['passed']}/{c['total']}"
            rows.append([name, c["name"], rate, c["against"]])
    md.append(_table(["Agent", "Check", "Passed", "Checked against"], rows))
    md.append("\nA 100% here usually means a regression guard against a written table, not a hard test. The last column says which.\n")

    md.append("## 3. Single-agent baseline\n")
    r = base["rules_single_agent"]
    ro = r["overall"]
    md.append(
        "One component that reads every feed, holds every tool and decides alone, using the same rule table.\n\n"
        + _table(["", "Accuracy", "Recall", "False-hold rate", "p50 latency", "p95 latency"],
                 [["Multi-agent graph", PCT(o["accuracy"]), PCT(o["recall"]), PCT(o["false_hold_rate"]), f"{lat['p50'] * 1000:.0f} ms", f"{lat['p95'] * 1000:.0f} ms"],
                  ["Single agent (rules)", PCT(ro["accuracy"]), PCT(ro["recall"]), PCT(ro["false_hold_rate"]), f"{r['latency_s']['p50'] * 1000:.0f} ms", f"{r['latency_s']['p95'] * 1000:.0f} ms"]])
        + f"\n\nSame decision as the multi-agent graph: {r['same_decision_as_multi_agent']}. "
        "Accuracy is the same because the decision comes from the same rules. The multi-agent graph is slower: it signs every handoff, "
        "writes events and keeps a record. That cost buys the separation below, not accuracy.\n"
    )
    m = base["model_single_agent"]
    if m["ran"]:
        mo = m["overall"]
        md.append(f"Model-only single agent, {m['cases']} cases: accuracy {PCT(mo['accuracy'])}, recall {PCT(mo['recall'])}, false-hold rate {PCT(mo['false_hold_rate'])}, p50 {m['latency_s']['p50'] * 1000:.0f} ms.\n")
    else:
        md.append(f"Model-only single agent: **not run.** {m['reason']}\n")
    reach = base["reach"]
    md.append("\n### What each part can reach\n")
    md.append(_table(["Agent", "Money-moving tools it can call"], [[k, ", ".join(v) or "none"] for k, v in reach["per_agent"].items()]
                     + [["**a single agent**", f"all {reach['single_agent_count']}: " + ", ".join(reach["single_agent"])]]))
    md.append(
        f"\nThe agents that read text typed by whoever sends the payment ({', '.join(reach['text_exposed_agents'])}) can reach "
        f"**{reach['multi_agent_max_for_text_exposed']}** money-moving tools. A single agent that reads the same text can reach **{reach['single_agent_count']}**. "
        "This is a design measurement, not a test result: it shows how much a manipulated agent could do.\n"
    )

    pe = res["profile_effect"]
    off, on = pe["off"], pe["on"]
    md.append("## 4. What the customer profile changed\n")
    md.append(
        "The same scenarios decided twice: once from the signals alone, once with the customer's own history (usual payees and amounts) "
        "taken into account. The profile only moves the score. It never touches the block-at-once rule or the swap-plus-warning-sign rule.\n\n"
        + _table(["", "Accuracy", "Precision", "Recall", "False-hold rate", "Missed-fraud rate"],
                 [["Signals only", PCT(off["accuracy"]), PCT(off["precision"]), PCT(off["recall"]), PCT(off["false_hold_rate"]), PCT(off["missed_fraud_rate"])],
                  ["With customer profile", PCT(on["accuracy"]), PCT(on["precision"]), PCT(on["recall"]), PCT(on["false_hold_rate"]), PCT(on["missed_fraud_rate"])]])
        + "\n"
    )
    offs = {a["archetype"]: a for a in pe["by_archetype_off"]}
    changed = [[a["archetype"], "fraud" if a["fraud"] else "legitimate", PCT(offs[a["archetype"]]["flag_rate"]), PCT(a["flag_rate"])] for a in pe["by_archetype_on"] if a["flag_rate"] != offs[a["archetype"]]["flag_rate"]]
    if changed:
        md.append("Scenario types whose flag rate moved:\n\n" + _table(["Scenario", "Truth", "Flagged before", "Flagged after"], changed) + "\n")
    d_recall = (on["recall"] or 0) - (off["recall"] or 0)
    d_hold = (on["false_hold_rate"] or 0) - (off["false_hold_rate"] or 0)
    md.append(
        f"\nWhat moved: recall changed by {d_recall * 100:+.1f} points and the false-hold rate by {d_hold * 100:+.1f} points. "
        "The profile lowers the score for an established payee and a usual amount, and raises it for an amount more than twice the customer's usual high shortly after a SIM change. "
        "The raise needs at least five earlier payments, so it stays quiet for customers with a short ledger. "
        "It does nothing for fraud that stays inside a customer's usual pattern. The histories here are invented, so the size of the change is not a prediction.\n"
    )

    cal = res["calibration"]
    md.append("## 5. The feedback loop, with a person in it\n")
    md.append(
        f"Customer answers to held payments are the only feedback signal. In this harness the answers are **{cal['answers']}**, so this checks the mechanism, not the world.\n\n"
    )
    if cal["evidence"]["bands"]:
        md.append(_table(["Score band", "Answered holds", "Fraud", "False holds", "Hold was right"],
                         [[f"{b['from']} to {b['to']}", b["cases"], b["fraud"], b["legitimate"], PCT(b["hold_was_right"])] for b in cal["evidence"]["bands"]]))
    if cal["proposals"]:
        md.append("\nThe Analytics agent proposed: " + "; ".join(f"hold score {p['current']} to {p['proposed']}" for p in cal["proposals"]) + ". It changes nothing until an analyst approves it.\n")
    else:
        md.append(f"\nThe Analytics agent made **no proposal**: it needs {cal['min_cases']} answered holds in the lowest band and no confirmed fraud in it. That is the guard working.\n")
    md.append("\nWhy the gate matters. What raising the hold score would have done on the same scenarios:\n\n")
    md.append(_table(["Hold score", "Recall", "False-hold rate", "Missed-fraud rate"],
                     [[k, PCT(v["recall"]), PCT(v["false_hold_rate"]), PCT(v["missed_fraud_rate"])] for k, v in cal["what_if_hold_score"].items()]))
    md.append("\nA higher score means fewer false holds and more missed fraud. The system cannot see missed fraud on its own, so a person decides.\n")

    md.append("## 6. Hostile text in the payee field\n")
    md.append(f"{inj['total']} runs: {len(inj['cases']) // 2} payloads against a routine payment and the same against a takeover. "
              f"Decision unchanged, nothing outside a charter, no raw identifiers sent to the model: **{inj['decision_unchanged_and_clean']} of {inj['total']}**.\n")
    bad = [c for c in inj["cases"] if not (c["same_decision"] and c["outside_charter"] == 0 and c["raw_identifiers_to_model"] == 0 and c["decision"] is not None)]
    if bad:
        md.append("\nRuns that were not clean:\n")
        md.append(_table(["Scenario", "Payload", "Decision", "Reference", "Case status"], [[b["scenario"], b["payload"].replace("|", "/").replace("\n", " "), b["decision"], b["reference"], b["status"]] for b in bad]))
    md.append(
        "\nWith the mock model nothing here can actually be talked into anything, because the mock ignores the text. "
        "What this checks is the code around the model: the decision does not depend on it, the privacy guard holds, and unusual text does not crash a step. "
        "Run it again with a real model key to test the model itself.\n"
    )

    m = res["mcp"]
    md.append("## 7. The same lookups through MCP\n")
    if m["ran"]:
        md.append(
            f"{m['cases']} scenarios run twice, once with direct tool calls and once with the Telecom and Banking lookups going through the Model Context Protocol (in-memory, one server per agent).\n\n"
            f"- Same decision, score and ledger result: **{m['same_decision_score_and_ledger']} of {m['cases']}**.\n"
            f"- Same set of tool calls: **{m['same_tool_calls']} of {m['cases']}**.\n"
            f"- Median time per case: {m['latency_s']['direct_p50'] * 1000:.0f} ms direct, {m['latency_s']['mcp_p50'] * 1000:.0f} ms through MCP. MCP calls made: {m['mcp_calls']}. Fallbacks to a direct call: {m['fallbacks_to_direct']}.\n"
            f"- Tools offered: telecom {len(m['offered']['telecom'])}, banking {len(m['offered']['banking'])}. Money-moving tools offered: **{len(m['money_tools_offered'])}**.\n\n"
            "MCP adds a standard way in and a second charter check. It does not change any outcome, and it costs time.\n"
        )
    else:
        md.append(f"Not run: {m['reason']}.\n")

    md.append("## 8. Limits\n")
    md.append("\n".join(f"- {t}" for t in [
        "Synthetic data and invented fraud patterns. The rules were written by the same team that wrote the red-team scenarios.",
        "No real fraud labels, so precision and recall describe the scenario mix, which we chose.",
        "The mock model is the default. Model-dependent behaviour is not measured unless a key is set.",
        "The selfie check compares two frames. It is not face recognition, and its numbers are for plumbing only.",
        "Latency is measured in-process on one machine with no step delay and no network.",
    ]))
    (out / "results.md").write_text("\n".join(md) + "\n")
    try:
        _charts(res, out)
    except ImportError:
        (out / "README-charts.txt").write_text("Install matplotlib (pip install -r evaluation/requirements.txt) to draw the charts.\n")


def _charts(res: dict, out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams["font.family"] = ["Carlito", "DejaVu Sans"]
    INK, TEAL, ORANGE, GREY = "#1f2933", "#0f6b6b", "#c2410c", "#9aa5b1"
    colours = {"benign": TEAL, "attack": ORANGE, "adversarial": "#7b341e"}

    arch = res["system"]["by_archetype"]
    fig, ax = plt.subplots(figsize=(8.6, 4.2))
    names = [a["archetype"].replace("_", " ") for a in arch]
    ax.bar(range(len(arch)), [a["flag_rate"] * 100 for a in arch], color=[colours[a["group"]] for a in arch], width=0.7)
    for i, a in enumerate(arch):
        ax.text(i, a["flag_rate"] * 100 + 2, f"{a['flag_rate'] * 100:.0f}", ha="center", fontsize=8, color=INK)
    ax.set_xticks(range(len(arch)))
    ax.set_xticklabels(names, rotation=40, ha="right", fontsize=8)
    ax.set_ylim(0, 112); ax.set_ylabel("% held or blocked", color=INK)
    for s in ("top", "right"): ax.spines[s].set_visible(False)
    handles = [plt.Rectangle((0, 0), 1, 1, color=c) for c in colours.values()]
    ax.legend(handles, ["legitimate", "attack the rules target", "adversarial (red team)"], frameon=False, fontsize=8, loc="lower left", bbox_to_anchor=(0, 1.0), ncol=3)
    ax.set_title("How often each scenario type is held or blocked", loc="right", fontsize=11, weight="bold", color=INK)
    fig.tight_layout(); fig.savefig(out / "flag-rate-by-scenario.png", dpi=170); plt.close(fig)

    fig, ax = plt.subplots(figsize=(7.6, 3.8))
    labels, vals = [], []
    for name, checks in res["agents"].items():
        p, t = sum(c["passed"] for c in checks), sum(c["total"] for c in checks)
        labels.append(f"{name}  ({p}/{t})"); vals.append(100 * p / t if t else 0)
    ax.barh(labels[::-1], vals[::-1], color=TEAL, height=0.6)
    ax.set_xlim(0, 100); ax.set_xlabel("% of checks passed", color=INK)
    for s in ("top", "right"): ax.spines[s].set_visible(False)
    ax.set_title("Each agent tested on its own", loc="left", fontsize=11, weight="bold", color=INK)
    fig.tight_layout(); fig.savefig(out / "single-agent-checks.png", dpi=170); plt.close(fig)

    multi, single = res["system"]["latency_s"], res["single_agent_baseline"]["rules_single_agent"]["latency_s"]
    fig, ax = plt.subplots(figsize=(6.2, 3.4))
    x = [0, 1]
    ax.bar([i - 0.18 for i in x], [multi["p50"] * 1000, multi["p95"] * 1000], 0.34, color=TEAL, label="multi-agent graph")
    ax.bar([i + 0.18 for i in x], [single["p50"] * 1000, single["p95"] * 1000], 0.34, color=GREY, label="single agent (rules)")
    ax.set_xticks(x); ax.set_xticklabels(["median", "95th percentile"]); ax.set_ylabel("ms per case", color=INK)
    for s in ("top", "right"): ax.spines[s].set_visible(False)
    ax.legend(frameon=False, fontsize=8)
    ax.set_title("Time to a decision", loc="left", fontsize=11, weight="bold", color=INK)
    fig.tight_layout(); fig.savefig(out / "latency.png", dpi=170); plt.close(fig)
